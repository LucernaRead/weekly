def main():
    texts = {}
    for fn in FILES:
        with open(os.path.join(HERE, fn), encoding="utf-8") as fh:
            texts[fn] = fh.read()

    def _apply(mapping, superseded=None):
        ordered = sorted(mapping.items(), key=lambda kv: -len(kv[0]))
        # Final form of an entry's destination: later (shorter) entries in the
        # same pass also rewrite parts of it (e.g. a f.ex line whose dst still
        # carries type "翻译" is rewritten by the generic "翻译"->"Переведите"
        # entry later in the pass). A re-run must therefore recognise the
        # final form, not just the immediate dst, as "already applied".
        def _final(dst, start):
            out = dst
            for s2, d2 in ordered[start + 1:]:
                out = out.replace(s2, d2)
            return out
        for idx, (src, dst) in enumerate(ordered):
            total = sum(t.count(src) for t in texts.values())
            if total == 0:
                final = _final(dst, idx)
                if any(dst in t or final in t for t in texts.values()):
                    print(f"skip (already applied): {src[:44]!r}")
                    continue
                if superseded:
                    shorts = {superseded[k] for k in (dst, final) if k in superseded}
                    if any(s in t for s in shorts for t in texts.values()):
                        print(f"skip (superseded by fix): {src[:44]!r}")
                        continue
                raise AssertionError(f"REPL source absent (already applied?): {src!r}")
            for fn in FILES:
                texts[fn] = texts[fn].replace(src, dst)
            assert not any(src in t for t in texts.values()), \
                f"REPL source still present after replace: {src!r}"
            print(f"ok x{total}: {src[:44]!r}")

    _apply(REPL, superseded=FIX2FIX3)
    print("--- fix2/fix3 sync phase ---")
    _apply(FIX2FIX3)
    for fn in FILES:
        with open(os.path.join(HERE, fn), "w", encoding="utf-8") as fh:
            fh.write(texts[fn])
    print("transform applied to", len(FILES), "files")

if __name__ == "__main__":
    main()
