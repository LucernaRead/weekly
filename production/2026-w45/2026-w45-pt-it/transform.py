def main():
    texts = {}
    for fn in FILES:
        with open(os.path.join(HERE, fn), encoding="utf-8") as fh:
            texts[fn] = fh.read()
    # dry-run counts first: abort before writing if any pair misses
    for old, new in PAIRS:
        total = sum(t.count(old) for t in texts.values())
        assert total >= 1, f"MISSING (0x): {old[:90]!r}"
        print(f"  {total:3d}x :: {old[:70]!r}")
    for fn in FILES:
        t = texts[fn]
        for old, new in PAIRS:
            t = t.replace(old, new)
        with open(os.path.join(HERE, fn), "w", encoding="utf-8") as fh:
            fh.write(t)
    print("transform applied to", len(FILES), "files")

if __name__ == "__main__":
    main()
