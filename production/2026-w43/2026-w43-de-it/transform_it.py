"""DE x IT fan-out transform: exact-count replacements on the copied core build.
German target text is never touched; only the explanation layer (Chinese -> Italian),
pairing furniture, registry types/instr tokens, and the typing items."""
import io, os, sys

D = os.path.dirname(os.path.abspath(__file__))
FAILS = []

def apply(fname, pairs):
    path = os.path.join(D, fname)
    with io.open(path, encoding="utf-8") as f:
        s = f.read()
    for old, new, cnt in pairs:
        n = s.count(old)
        if n != cnt:
            FAILS.append(f"{fname}: expected {cnt}x but found {n}x :: {old[:60]!r}")
            continue
        s = s.replace(old, new)
    with io.open(path, "w", encoding="utf-8") as f:
        f.write(s)
    print(f"{fname}: {len(pairs)} rules applied")

